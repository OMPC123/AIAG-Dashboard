  const LANGS = [
    { code: 'zh-TW', name: '繁體中文' },
    { code: 'en', name: 'English' },
  ];

  /** 'auto' + a system locale ("zh-TW", "zh-Hant-TW", "en-US", ...) -> a supported code */
  function resolveLang(setting, locale) {
    if (setting && setting !== 'auto' && DICT[setting]) return setting;
    return /^zh/i.test(locale || '') ? 'zh-TW' : 'en';
  }

  function create(lang) {
    const dict = DICT[lang] || DICT.en;
    const t = (key, vars) => {
      let s = dict[key] ?? DICT.en[key] ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
      return s;
    };
    t.lang = lang;
    return t;
  }

  const api = { DICT, LANGS, resolveLang, create };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18N = api;
